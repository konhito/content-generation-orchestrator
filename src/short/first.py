def _build_meme_items(raw: dict, script_beats: list[dict], profile: dict) -> list[dict]:
    moments = raw.get("meme_moments") or []
    editing = get_editing_config(profile)
    low, high = editing.get("meme_beats", [1, 3])
    beat_target = max(2, len(script_beats) // 4)
    target = max(low, min(high, max(len(moments), beat_target)))
    items: list[dict] = []
    for index, moment in enumerate(moments[:target]):
        if not isinstance(moment, dict):
            continue
        beat = script_beats[index % len(script_beats)] if script_beats else {}
        items.append({
            "type": "meme",
            "query": moment.get("query") or moment.get("caption") or beat.get("script_text", "reaction"),
            "template_hint": moment.get("template_hint") or moment.get("meme_type") or "surprised",
            "meme_text_top": moment.get("meme_text_top") or "WAIT WHAT",
            "meme_text_bottom": moment.get("meme_text_bottom") or "IT GETS WORSE",
            "time_start": moment.get("time_start", moment.get("start", 0)),
            "time_end": moment.get("time_end", moment.get("end", 0)),
        })
    while len(items) < target and script_beats:
        beat = script_beats[len(items) % len(script_beats)]
        items.append({
            "type": "meme",
            "query": beat.get("script_text", "reaction"),
            "template_hint": "surprised",
            "meme_text_top": "WAIT WHAT",
            "meme_text_bottom": "IT GETS WORSE",
        })
    return items


def _beat_duration(beat: Any, total_duration: int, beat_count: int, index: int) -> float:
    if isinstance(beat, dict):
        start = beat.get("start")
        end = beat.get("end")
        if start is not None and end is not None:
            return max(1.0, float(end) - float(start))
    return total_duration / max(1, beat_count or index + 1)


def _enforce_narration_budget(narration: str, cta: str, duration_seconds: float) -> str:
    """Hard-cap narration at 132 WPM while preferring complete sentences."""
    max_total_words = max(1, int(duration_seconds * 2.2))
    narration_budget = max(1, max_total_words - len(cta.split()))
    words = narration.split()
    if len(words) <= narration_budget:
        return narration.strip()

    candidate = words[:narration_budget]
    sentence_end = next(
        (
            index
            for index in range(len(candidate) - 1, max(-1, len(candidate) // 2 - 1), -1)
            if candidate[index].endswith((".", "!", "?"))
        ),
        None,
    )
    if sentence_end is not None:
        candidate = candidate[: sentence_end + 1]
    elif candidate:
        candidate[-1] = candidate[-1].rstrip(",;:") + "."
    return " ".join(candidate)


