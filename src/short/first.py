@dataclass
class ResearchNote:
    """A normalized research/source note for short script prompting."""

    source: str
    title: str
    snippet: str
    url: str = ""
    score: float = 0.0
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass
class ResearchBundle:
    """Research context passed into the short-first LLM prompt."""

    topic: str
    niche: str
    notes: list[ResearchNote]

    def to_prompt_text(self) -> str:
        lines = [f"Topic: {self.topic}", f"Niche: {self.niche}"]
        for index, note in enumerate(self.notes, start=1):
            source = f"{note.source}: {note.title}".strip(": ")
            lines.append(f"{index}. [{source}] {note.snippet}")
            if note.url:
                lines.append(f"   URL: {note.url}")
        return "\n".join(lines)


@dataclass
class NicheProfile:
    """Guidance for shaping a short for a content niche."""

    name: str
    tone: str
    hook_style: str
    pacing: str
    caption_style: str
    cta_style: str
    meme_density: str = "medium"
    target_duration_seconds: int = 50


@dataclass
class MemeMoment:
    """A structured meme/editing moment, never raw JSX."""

    time_start: float
    time_end: float
    meme_type: str
    caption: str
    visual_style: str
    reason: str = ""


@dataclass
class ShortFirstResult:
    """Files generated by short-first script creation."""

    success: bool
    variant: str
    research_path: Path
    short_script_path: Path
    short_script_md_path: Path
    meme_plan_path: Path
    script_beats_path: Path | None = None
    component_plan_path: Path | None = None
    beat_mode_plan_path: Path | None = None
    character_plan_path: Path | None = None
    scene_recipe_plan_path: Path | None = None
    error: str | None = None


