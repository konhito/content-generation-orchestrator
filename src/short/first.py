"""Short-first generation from a topic, source docs, niche, and meme plan.

This module is intentionally separate from the long-video pipeline. It writes
only under a short variant directory and produces the same ``ShortScript`` shape
the existing shorts voiceover/storyboard/render code already understands.
"""

