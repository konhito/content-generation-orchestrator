def _seriousness_score(project_id: str, topic: str, niche: str) -> float:
    text = f"{project_id} {topic} {niche}".lower()
    serious_terms = (
        "war",
        "death",
        "disaster",
        "election",
        "violence",
        "crime",
        "disease",
        "politics",
    )
    return 0.9 if any(term in text for term in serious_terms) else 0.0


