def _format_short_script_markdown(
    short_script: ShortScript,
    beats: list[Any],
    profile: NicheProfile,
) -> str:
    lines = [
        f"# {short_script.title}",
        "",
        f"Niche: {profile.name}",
        f"Target duration: {short_script.total_duration_seconds:.0f}s",
        "",
        "## Hook",
        "",
        short_script.hook_question,
        "",
        "## Narration",
        "",
        short_script.condensed_narration,
        "",
        "## Beats",
        "",
    ]
    for index, beat in enumerate(beats or [], start=1):
        if isinstance(beat, dict):
            caption = beat.get("caption", "")
            visual = beat.get("visual", "")
        else:
            caption = str(beat)
            visual = ""
        lines.append(f"{index}. {caption} — {visual}".strip())
    lines.extend(["", "## CTA", "", short_script.cta_narration, ""])
    return "\n".join(lines)


